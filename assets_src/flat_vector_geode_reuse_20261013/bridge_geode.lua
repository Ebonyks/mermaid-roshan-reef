local s=assert(app.open(app.params.source))
assert(s.width==1254 and s.height==1254 and #s.frames==1 and #s.layers==1)
s.layers[1].name="Complete preserved closed geode"
s:saveAs(app.params.native_master)
s:close()
local original=assert(app.open(app.params.native_master))
local native=Image(original.width,original.height,ColorMode.RGB)
native:drawSprite(original,1)
native:saveAs(app.params.native_roundtrip)
assert(original.width*1024==original.height*1024,"Nonuniform normalization forbidden")
app.command.SpriteSize{ui=false,width=1024,height=1024,method="bilinear"}
original:saveAs(app.params.normalized_master)
original:close()
local normalized=assert(app.open(app.params.normalized_master))
assert(normalized.width==1024 and normalized.height==1024 and #normalized.frames==1 and #normalized.layers==1)
local output=Image(normalized.width,normalized.height,ColorMode.RGB)
output:drawSprite(normalized,1)
output:saveAs(app.params.output)
local proof=assert(io.open(app.params.proof,"wb"))
proof:write(json.encode{native_size={1254,1254},normalized_size={1024,1024},layers=#normalized.layers,frames=#normalized.frames,method="bilinear",crop=false,recolor=false,redraw=false,part_separation=false})
proof:close();normalized:close()
